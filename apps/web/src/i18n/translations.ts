export const DICTIONARIES: Record<Locale, Dictionary> = { fr, en, mg };

/** Valeur par défaut : clé elle-même, pour rendre les traductions manquantes visibles. */
export function translate(locale: Locale, key: string, fallback?: string): string {
  return DICTIONARIES[locale][key] ?? DICTIONARIES.fr[key] ?? fallback ?? key;
}

/**
 * Textes français → clé de traduction. Permet de traduire automatiquement les
 * titres et sous-titres existants (`PageHeader`) sans modifier chaque page.
 */
export const TEXT_TO_KEY: Record<string, string> = Object.entries(fr).reduce<Record<string, string>>(
  (map, [key, value]) => {
    if (value.length >= 3 && map[value] === undefined) map[value] = key;
    return map;
  },
  {},
);

/** Clé de traduction correspondant à un texte français, le cas échéant. */
export function keyForText(text: string | undefined | null): string | undefined {
  if (!text) return undefined;
  return TEXT_TO_KEY[text.trim()];
}
